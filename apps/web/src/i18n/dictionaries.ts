export const translate = (
  locale: Locale,
  key: TranslationKey,
  source: Partial<Record<Locale, Partial<CompleteDictionary>>> = dictionaries,
): string => source[locale]?.[key] ?? source.en?.[key] ?? dictionaries.en[key];
